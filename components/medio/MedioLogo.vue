<!--
  Medio — the wordmark: the brand name from kalio-brand.ts (the one line to
  change) in lower case, white and heavy, on a red rounded tile like a badge.
  The tile is the brand colour (--md-brand), so a palette or a merchant's
  brand colour repaints it. With no brand name set, the shop's own title is
  drawn the same way.
-->
<template>
  <component :is="to ? 'router-link' : 'span'" :aria-label="`${word} home`" :to="to" class="md-logo">
    <span class="md-logo__w">{{ word }}</span>
  </component>
</template>

<script>
import { BRAND } from "../kalio/kalio-brand";

export default {
  name: "MedioLogo",
  inject: { $shop: { default: null } },
  props: {
    to: { type: [Object, String], default: () => ({ path: "/" }) },
  },
  computed: {
    word() {
      return (BRAND.name || this.$shop?.title || "").toLowerCase();
    },
  },
};
</script>
